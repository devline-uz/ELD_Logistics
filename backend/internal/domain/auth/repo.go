// SystemSettings implements Repo.
func (r *PgRepo) SystemSettings(ctx context.Context) (map[string][]byte, error) {
	out := map[string][]byte{}
	err := r.tx(ctx, func(q *db.Queries) error {
		rows, err := q.ListSystemSettings(ctx)
		if err != nil {
			return err
		}
		for _, s := range rows {
			out[s.Key] = s.Value
		}
		return nil
	})
	return out, err
}

func nilIfEmpty(v string) *string {
	if v == "" {
		return nil
	}
	return &v
}

func parseIP(v string) *netip.Addr {
	if v == "" {
		return nil
	}
	addr, err := netip.ParseAddr(v)
	if err != nil {
		return nil
	}
	return &addr
}
