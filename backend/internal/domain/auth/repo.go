// MarkLoginFailure implements Repo.
func (r *PgRepo) MarkLoginFailure(ctx context.Context, userID uuid.UUID, threshold, lockMinutes int32) (int32, *time.Time, error) {
	var row db.MarkUserLoginFailureRow
	err := r.tx(ctx, func(q *db.Queries) error {
		var err error
		row, err = q.MarkUserLoginFailure(ctx, db.MarkUserLoginFailureParams{
			ID: userID, Column2: threshold, Column3: lockMinutes,
		})
		return err
	})
	if err != nil {
		return 0, nil, err
	}
	return row.FailedLogins, pgconv.ToTimePtr(row.LockedUntil), nil
}

// CreateSession implements Repo.
func (r *PgRepo) CreateSession(ctx context.Context, in NewSessionInput) (db.Session, error) {
	var out db.Session
	err := r.tx(ctx, func(q *db.Queries) error {
		var err error
		out, err = q.CreateSession(ctx, db.CreateSessionParams{
			CompanyID:        pgconv.UUIDPtr(in.CompanyID),
			UserID:           in.UserID,
			DeviceID:         nilIfEmpty(in.DeviceID),
			DeviceType:       in.DeviceType,
			RefreshTokenHash: in.TokenHash,
			ExpiresAt:        in.ExpiresAt.UTC(),
			AppVersion:       nilIfEmpty(in.AppVersion),
			Ip:               parseIP(in.IP),
			UserAgent:        nilIfEmpty(in.UserAgent),
		})
		return err
	})
	return out, err
}

