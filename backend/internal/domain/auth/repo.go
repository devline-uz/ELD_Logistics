// SessionMatch is the result of looking a refresh token hash up. Current is
// false when the hash matched the previous, already rotated value, which is
// exactly the refresh token reuse signal.
type SessionMatch struct {
	Session db.Session
	Current bool
}

// NewSessionInput describes the session a successful login creates.
type NewSessionInput struct {
	CompanyID  *uuid.UUID
	UserID     uuid.UUID
	DeviceID   string
	DeviceType string
	TokenHash  string
	ExpiresAt  time.Time
	AppVersion string
	IP         string
	UserAgent  string
}

// InvitationInput describes an invitation or password reset token.
type InvitationInput struct {
	CompanyID *uuid.UUID
	UserID    uuid.UUID
	TokenHash string
	Channel   string
	Purpose   string
	ExpiresAt time.Time
}

// Invitation purposes mirrored from the invitations.purpose CHECK constraint.
const (
	PurposeInvitation    = "invitation"
	PurposePasswordReset = "password_reset"
)

// Repo is everything the auth service needs from storage. Every method is
// parameterised SQL generated by sqlc; no statement is ever concatenated.
type Repo interface {
	FindUsersByLogin(ctx context.Context, login string) ([]db.User, error)
	GetUserByID(ctx context.Context, id uuid.UUID) (db.User, error)
	GetRoleByID(ctx context.Context, id uuid.UUID) (db.Role, error)
	RolePermissions(ctx context.Context, roleID uuid.UUID) ([]string, error)
	GetCompany(ctx context.Context, id uuid.UUID) (db.Company, error)

	MarkLoginSuccess(ctx context.Context, userID uuid.UUID) error
	MarkLoginFailure(ctx context.Context, userID uuid.UUID, threshold, lockMinutes int32) (int32, *time.Time, error)

	CreateSession(ctx context.Context, in NewSessionInput) (db.Session, error)
	ReplaceDeviceSessions(ctx context.Context, userID uuid.UUID, deviceType, reason string) ([]uuid.UUID, error)
	SessionByRefreshHash(ctx context.Context, hash string) (SessionMatch, error)
	RotateSession(ctx context.Context, id uuid.UUID, newHash string, expiresAt time.Time, appVersion string) (db.Session, error)
	RevokeSession(ctx context.Context, id uuid.UUID, reason string) error
	RevokeAllUserSessions(ctx context.Context, userID uuid.UUID, reason string) ([]uuid.UUID, error)
	PauseSession(ctx context.Context, id uuid.UUID) error
	ResumeSession(ctx context.Context, id uuid.UUID) error
	GetSession(ctx context.Context, id uuid.UUID) (db.Session, error)
	ListSessionsByUser(ctx context.Context, userID uuid.UUID) ([]db.Session, error)

	SetUserPassword(ctx context.Context, userID uuid.UUID, hash string) error
	SetUserPIN(ctx context.Context, userID uuid.UUID, hash string) error
	SetUserTOTP(ctx context.Context, userID uuid.UUID, secretEnc string, enabled bool, recovery []string) error

	CreateInvitation(ctx context.Context, in InvitationInput) (db.Invitation, error)
	InvitationByTokenHash(ctx context.Context, hash string) (db.Invitation, error)
	MarkInvitationUsed(ctx context.Context, id uuid.UUID) error
	InvalidateUserInvitations(ctx context.Context, userID uuid.UUID, purpose string) error

	SystemSettings(ctx context.Context) (map[string][]byte, error)
}

// PgRepo is the pgx/sqlc implementation of Repo.
//
// Authentication runs before a tenant is known, so every statement executes
// inside Pool.WithAuthTx: it opens the narrow app.auth_stage RLS window that
// migration 00013 defines. Application level filtering (company_id, user_id)
// still happens in the queries themselves.
type PgRepo struct {
	pool *db.Pool
}

// NewRepo builds the storage adapter.
func NewRepo(pool *db.Pool) *PgRepo { return &PgRepo{pool: pool} }

func (r *PgRepo) tx(ctx context.Context, fn func(q *db.Queries) error) error {
	return r.pool.WithAuthTx(ctx, func(tx pgx.Tx) error {
		return fn(db.New(tx))
	})
}

// FindUsersByLogin implements Repo.
func (r *PgRepo) FindUsersByLogin(ctx context.Context, login string) ([]db.User, error) {
	var out []db.User
	err := r.tx(ctx, func(q *db.Queries) error {
		rows, err := q.FindUsersByLogin(ctx, login)
		out = rows
		return err
	})
	return out, err
}

