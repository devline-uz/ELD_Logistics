// SessionByRefreshHash implements Repo.
func (r *PgRepo) SessionByRefreshHash(ctx context.Context, hash string) (SessionMatch, error) {
	var m SessionMatch
	err := r.tx(ctx, func(q *db.Queries) error {
		row, err := q.GetSessionByAnyRefreshHash(ctx, hash)
		if err != nil {
			return err
		}
		m = SessionMatch{
			Current: row.IsCurrent,
			Session: db.Session{
				ID: row.ID, CompanyID: row.CompanyID, UserID: row.UserID,
				DeviceID: row.DeviceID, DeviceType: row.DeviceType,
				RefreshTokenHash: row.RefreshTokenHash, Status: row.Status,
				RevokedReason: row.RevokedReason, ExpiresAt: row.ExpiresAt,
				LastSeenAt: row.LastSeenAt, AppVersion: row.AppVersion,
				Ip: row.Ip, UserAgent: row.UserAgent,
				CreatedAt: row.CreatedAt, UpdatedAt: row.UpdatedAt,
			},
		}
		return nil
	})
	return m, err
}

